import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import type { Plugin } from 'vite'

/**
 * Production HTTP headers for the static frontend (FIT-10), written to `dist/_headers`
 * (the format used by Cloudflare Pages, also understood by Netlify).
 *
 * The Content Security Policy is generated from the built index.html, so the hash of the
 * inline theme script always matches the shipped file, and from VITE_API_BASE_URL, so the
 * browser may only connect to this site and the configured API origin.
 */

/** Origin of an absolute http(s) API base URL; null for same-origin paths ("/api") or empty values. */
export function apiOriginFrom(apiBaseUrl: string | undefined): string | null {
  const value = apiBaseUrl?.trim()
  if (!value || value.startsWith('/')) return null
  const url = new URL(value)
  if (url.protocol !== 'https:' && url.protocol !== 'http:') throw new Error(`Unsupported API base URL protocol: ${url.protocol}`)
  return url.origin
}

/** CSP source expressions ('sha256-…') for every inline <script> (no src) in the HTML. */
export function inlineScriptHashes(html: string): string[] {
  const hashes: string[] = []
  for (const match of html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/gi)) {
    const [, attributes = '', content = ''] = match
    if (/\bsrc\s*=/i.test(attributes)) continue
    hashes.push(`'sha256-${createHash('sha256').update(content, 'utf8').digest('base64')}'`)
  }
  return hashes
}

export function buildContentSecurityPolicy({ apiOrigin, scriptHashes }: { apiOrigin: string | null; scriptHashes: readonly string[] }): string {
  const directives: Record<string, string[]> = {
    'default-src': ["'self'"],
    'script-src': ["'self'", ...scriptHashes],
    // Tailwind output is a static file; React sets inline styles through the DOM (allowed without 'unsafe-inline').
    'style-src': ["'self'"],
    'img-src': ["'self'", 'data:'],
    'font-src': ["'self'"],
    'connect-src': ["'self'", ...(apiOrigin ? [apiOrigin] : [])],
    'manifest-src': ["'self'"],
    'worker-src': ["'self'"],
    'object-src': ["'none'"],
    'base-uri': ["'self'"],
    'form-action': ["'self'"],
    'frame-ancestors': ["'none'"],
    'upgrade-insecure-requests': [],
  }
  return Object.entries(directives)
    .map(([name, values]) => [name, ...values].join(' '))
    .join('; ')
}

export function buildHeadersFile(csp: string): string {
  return `# Generated by deploy/security-headers.ts during \`npm run build\`. Do not edit.
/*
  Content-Security-Policy: ${csp}
  Strict-Transport-Security: max-age=31536000; includeSubDomains
  X-Frame-Options: DENY
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  Cross-Origin-Opener-Policy: same-origin
  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=()

# Content-hashed build output never changes under the same name.
/assets/*
  Cache-Control: public, max-age=31536000, immutable

# Always revalidate the service worker and the files that point to a version.
/sw.js
  Cache-Control: no-cache
/index.html
  Cache-Control: no-cache
/manifest.webmanifest
  Cache-Control: no-cache
`
}

/** Vite plugin: writes `_headers` next to the built index.html (production builds only). */
export function securityHeaders({ apiBaseUrl }: { apiBaseUrl: string | undefined }): Plugin {
  let outDir = 'dist'
  return {
    name: 'fitness-ai:security-headers',
    apply: 'build',
    configResolved(config) {
      outDir = config.build.outDir.startsWith('/') ? config.build.outDir : join(config.root, config.build.outDir)
    },
    writeBundle() {
      const html = readFileSync(join(outDir, 'index.html'), 'utf8')
      const csp = buildContentSecurityPolicy({ apiOrigin: apiOriginFrom(apiBaseUrl), scriptHashes: inlineScriptHashes(html) })
      writeFileSync(join(outDir, '_headers'), buildHeadersFile(csp))
    },
  }
}
